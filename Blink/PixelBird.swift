            ".##...............###........",
            "..##..............###........",
            "..###.....##########.........",
            "...###..############.........",
            "#...###############..........",
            ".##..##############..........",
            "...################..........",
            ".....##############..........",
            ".....##############..........",
            ".....#############...........",
            "......##########.............",
