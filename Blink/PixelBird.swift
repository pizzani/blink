/// An original pixel-art running bird (long legs, swept-back crest, tail fan)
/// that sprints across the menu bar icon from left to right.
@MainActor
enum PixelBird {
    /// Run cycle: full stride, then legs passing (body bobs down a pixel).
    private static let poses = [
        [
